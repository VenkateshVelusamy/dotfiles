local setup_treesitter = function()
	local treesitter = require("nvim-treesitter")
	treesitter.setup({})
	local ensure_installed = {
		"vim",
		"vimdoc",
		"rust",
		"c",
		"cpp",
		"go",
		"html",
		"css",
		"javascript",
		"json",
		"lua",
		"markdown",
		"python",
		"typescript",
		"vue",
		"svelte",
		"bash",
	}

	local config = require("nvim-treesitter.config")

	local already_installed = config.get_installed()
	local parsers_to_install = {}

	for _, parser in ipairs(ensure_installed) do
		if not vim.tbl_contains(already_installed, parser) then
			table.insert(parsers_to_install, parser)
		end
	end

	if #parsers_to_install > 0 then
		treesitter.install(parsers_to_install)
	end

	local group = vim.api.nvim_create_augroup("TreeSitterConfig", { clear = true })
	vim.api.nvim_create_autocmd("FileType", {
		group = group,
		callback = function(args)
			if vim.list_contains(config.get_installed(), vim.treesitter.language.get_lang(args.match)) then
				vim.treesitter.start(args.buf)
			end
		end,
	})
end

setup_treesitter()

local function get_notes_path()
  -- Never error() here: this runs at startup, so a bad path would abort the rest
  -- of init. Detect the OS via vim (portable), not /etc/os-release (absent on mac).
  if vim.fn.has("mac") == 1 then
    return vim.fn.expand("~/Documents/Notes")
  end
  local os_release = vim.fn.system("cat /etc/os-release 2>/dev/null")
  if os_release:match("Ubuntu") then
    return "/mnt/c/Users/Rad/Documents/Notes"
  end
  -- Artix and any other unix: default under HOME.
  return vim.fn.expand("~/Documents/Notes")
end

