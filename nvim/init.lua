-- Git branch for the statusline. Prefer mini.git's buffer-local head (event-driven,
-- no subprocess); fall back to a cached `git` call only when it isn't populated yet.
local cached_branch = ""
local last_check = 0
local function git_branch()
	local mg = vim.b.minigit_summary
	local branch = mg and mg.head_name or ""
	if branch == "" then
		local now = vim.uv.now()
		if now - last_check > 5000 then -- refresh the fallback at most every 5s
			cached_branch = vim.fn.system("git branch --show-current 2>/dev/null | tr -d '\n'")
			last_check = now
		end
		branch = cached_branch
	end
	if branch ~= "" then
		return " \u{e725} " .. branch .. " " -- nf-dev-git_branch
	end
	return ""
end

